#for loop used to iterate through a sequence (list,tuple dictionary,set)
#loop through a list
fruits= ["oranges","mangoes","kiwis","pineapples"]
for fruit in fruits:
    print(fruit)
#loop through a string
for x in "python":
    print(x)  
#loop through a range()
for y in range(7):
    print(y)
# loop through a range (start,stop)
for z in range(5,11):
    print(z)
#step range (start,stop,step)
for a in range(20,30,2):
    print(a)    